import { and, eq } from "drizzle-orm";
import { z } from "zod";
import type { Database } from "./client.js";
import { accounts, memberships, organizations, sessions, users } from "./schema.js";
import { requireOrganizationId, requireOrganizationName, requireUserId, UserScopeError } from "./scope.js";

const organizationColumns = {
  id: organizations.id,
  name: organizations.name,
  createdAt: organizations.createdAt,
  updatedAt: organizations.updatedAt,
};

export function organizationByIdQuery(db: Database, organizationId: unknown) {
  const scopedOrganizationId = requireOrganizationId(organizationId);
  return db
    .select()
    .from(organizations)
    .where(eq(organizations.id, scopedOrganizationId))
    .limit(1);
}

export async function getOrganization(db: Database, organizationId: unknown) {
  const rows = await organizationByIdQuery(db, organizationId);
  return rows[0] ?? null;
}

export function membershipsForOrganizationQuery(db: Database, organizationId: unknown) {
  const scopedOrganizationId = requireOrganizationId(organizationId);
  return db
    .select()
    .from(memberships)
    .where(eq(memberships.organizationId, scopedOrganizationId));
}

export async function listMembershipsForOrganization(db: Database, organizationId: unknown) {
  return membershipsForOrganizationQuery(db, organizationId);
}

export function usersInOrganizationQuery(db: Database, organizationId: unknown) {
  const scopedOrganizationId = requireOrganizationId(organizationId);
  return db
    .select({
      id: users.id,
      email: users.email,
      name: users.name,
      role: memberships.role,
      membershipId: memberships.id,
    })
    .from(memberships)
    .innerJoin(users, eq(users.id, memberships.userId))
    .where(eq(memberships.organizationId, scopedOrganizationId));
}

export async function listUsersInOrganization(db: Database, organizationId: unknown) {
  return usersInOrganizationQuery(db, organizationId);
}

/**
 * Organizations visible to one user. Membership is required; a client-supplied
 * organization id is not used here.
 */
export function organizationsForMemberQuery(db: Database, userId: unknown) {
  const scopedUserId = requireUserId(userId);
  return db
    .select(organizationColumns)
    .from(memberships)
    .innerJoin(organizations, eq(organizations.id, memberships.organizationId))
    .where(eq(memberships.userId, scopedUserId));
}

export async function listOrganizationsForMember(db: Database, userId: unknown) {
  return organizationsForMemberQuery(db, userId);
}

/**
 * One organization, and only when the user has a membership in it.
 */
export function organizationForMemberQuery(
  db: Database,
  organizationId: unknown,
  userId: unknown,
) {
  const scopedOrganizationId = requireOrganizationId(organizationId);
  const scopedUserId = requireUserId(userId);
  return db
    .select(organizationColumns)
    .from(memberships)
    .innerJoin(organizations, eq(organizations.id, memberships.organizationId))
    .where(
      and(
        eq(memberships.organizationId, scopedOrganizationId),
        eq(memberships.userId, scopedUserId),
      ),
    )
    .limit(1);
}

export async function getOrganizationForMember(
  db: Database,
  organizationId: unknown,
  userId: unknown,
) {
  const rows = await organizationForMemberQuery(db, organizationId, userId);
  return rows[0] ?? null;
}

/**
 * Creates one organization and an owner membership for the signed-in user.
 * The organization id is generated by the database.
 */
export async function createOrganizationForMember(
  db: Database,
  input: { userId: unknown; name: unknown },
) {
  const userId = requireUserId(input.userId);
  const name = requireOrganizationName(input.name);
  return db.transaction(async (tx) => {
    const inserted = await tx.insert(organizations).values({ name }).returning({
      id: organizations.id,
      name: organizations.name,
      createdAt: organizations.createdAt,
      updatedAt: organizations.updatedAt,
    });
    const organization = inserted[0];
    if (!organization) {
      throw new Error("organization was not created");
    }
    await tx.insert(memberships).values({
      organizationId: organization.id,
      userId,
      role: "owner",
    });
    return organization;
  });
}

/** Counts sessions for a user. The session token is not selected. */
export async function countSessionsForUser(db: Database, userId: unknown): Promise<number> {
  const scopedUserId = requireUserId(userId);
  const rows = await db
    .select({ id: sessions.id })
    .from(sessions)
    .where(eq(sessions.userId, scopedUserId));
  return rows.length;
}

/**
 * The stored credential hash for a user, when one exists.
 * Callers must not log the returned value.
 */
export async function credentialPasswordHash(db: Database, userId: unknown): Promise<string | null> {
  const scopedUserId = requireUserId(userId);
  const rows = await db
    .select({ password: accounts.password })
    .from(accounts)
    .where(and(eq(accounts.userId, scopedUserId), eq(accounts.providerId, "credential")))
    .limit(1);
  return rows[0]?.password ?? null;
}

const emailSchema = z.string().trim().regex(/^[^\s@]+@[^\s@]+$/);

/**
 * Deletes one user. Sessions, accounts, and memberships cascade.
 * Organizations that then have no members are deleted too.
 */
export async function removeUserByEmail(db: Database, email: unknown): Promise<void> {
  const parsed = emailSchema.safeParse(email);
  if (!parsed.success) {
    throw new UserScopeError();
  }
  const found = await db
    .select({ id: users.id })
    .from(users)
    .where(eq(users.email, parsed.data));
  const user = found[0];
  if (!user) {
    return;
  }
  const memberOf = await db
    .select({ organizationId: memberships.organizationId })
    .from(memberships)
    .where(eq(memberships.userId, user.id));
  await db.delete(users).where(eq(users.id, user.id));
  for (const row of memberOf) {
    const remaining = await db
      .select({ id: memberships.id })
      .from(memberships)
      .where(eq(memberships.organizationId, row.organizationId));
    if (remaining.length === 0) {
      await db.delete(organizations).where(eq(organizations.id, row.organizationId));
    }
  }
}
